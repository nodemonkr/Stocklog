def seed(db: Session) -> None:
    # 1. 최초 관리자 계정 생성
    if not db.query(User).filter(User.username == "admin").first():
        db.add(
            User(
                username="admin",
                password_hash=hash_password("admin"),
                display_name="관리자",
                is_admin=True,
                membership_tier="ADMIN",
            )
        )
        flush_or_rollback(db)

    # 2. 최초 종목 식별정보만 생성 (숫자 데이터는 실제 API에서만 수집)
    if db.query(Stock).count() == 0:
        for idx, row in enumerate(STOCKS):
            (
                code,
                name,
                market,
                sector,
                price,
                chg,
                cap,
                per,
                pbr,
                roe,
                growth,
                margin,
                div,
                mom,
                vol,
                corp,
            ) = row

            stock = Stock(
                code=code,
                name=name,
                market=market,
                sector=sector,
                price=0,
                change_rate=0,
                market_cap=0,
                per=None,
                pbr=None,
                eps=None,
                bps=None,
                roe=None,
                revenue_growth=None,
                operating_margin=None,
                dividend_yield=None,
                momentum_20d=None,
                volatility=None,
                corp_code=corp,
            )

            stock.category = classify_stock(stock)
            stock.score = compute_score(stock)[0]

            db.add(stock)

        # 뒤의 count()에서 위 INSERT들이 보이도록 flush
        flush_or_rollback(db)

    # 3. 데모 차트/재무/뉴스 데이터는 생성하지 않습니다.

    # 4. 동기화 상태 레코드 생성
    if not (
        db.query(SyncState)
        .filter(SyncState.key == "stocks")
        .first()
    ):
        db.add(SyncState(key="stocks"))

    commit_or_rollback(db)
